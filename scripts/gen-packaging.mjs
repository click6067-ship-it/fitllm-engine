#!/usr/bin/env node
// Homebrew formula + Scoop manifest 생성기.
//
// 손으로 적지 않는 이유: 이 파일들은 URL 과 sha256 을 담는데, 그 둘이 실제 릴리스 자산과
// 어긋나면 `brew install` 이 체크섬 에러로 죽거나(운이 좋은 경우) 다른 바이트를 설치한다.
// 그래서 build-binaries.mjs 가 낸 manifest.json 에서만 값을 읽고, 없는 타깃은 조용히
// 건너뛰지 않고 에러를 낸다.
//
// usage: node scripts/gen-packaging.mjs --manifest dist-bin/manifest.json [--out packaging]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'click6067-ship-it/fitllm-engine';

const REQUIRED = Object.freeze([
  ['darwin', 'arm64', null],
  ['darwin', 'x64', null],
  ['linux', 'arm64', 'gnu'],
  ['linux', 'x64', 'gnu'],
  ['windows', 'x64', null],
]);

function pick(manifest, os, arch, libc) {
  const found = manifest.assets.find((a) => a.os === os && a.arch === arch && a.libc === libc);
  if (!found) throw new Error(`release manifest is missing ${os}/${arch}${libc ? `-${libc}` : ''} — refusing to emit a packaging file that points at nothing`);
  return found;
}

const url = (version, name) => `https://github.com/${REPO}/releases/download/v${version}/${name}`;

export function renderFormula(manifest) {
  const v = manifest.version;
  const [da, dx, la, lx] = [
    pick(manifest, 'darwin', 'arm64', null),
    pick(manifest, 'darwin', 'x64', null),
    pick(manifest, 'linux', 'arm64', 'gnu'),
    pick(manifest, 'linux', 'x64', 'gnu'),
  ];
  return `# Generated by scripts/gen-packaging.mjs — do not edit by hand.
# Tap install:
#   brew tap ${REPO.split('/')[0]}/fitllm https://github.com/${REPO}
#   brew install fitllm
#
# This is a binary formula. homebrew-core does not accept prebuilt binaries and
# its notability bar for self-submitted projects is 225 stars / 90 forks /
# 90 watchers, which this project does not meet — so a tap is the honest home
# for it today, not a workaround we are hiding.
class Fitllm < Formula
  desc "Will this LLM fit on your GPU or Mac? Architecture-accurate memory estimates"
  homepage "https://fitllm.run"
  version "${v}"
  license "MIT"

  on_macos do
    on_arm do
      url "${url(v, da.name)}"
      sha256 "${da.sha256}"
    end
    on_intel do
      url "${url(v, dx.name)}"
      sha256 "${dx.sha256}"
    end
  end

  on_linux do
    on_arm do
      url "${url(v, la.name)}"
      sha256 "${la.sha256}"
    end
    on_intel do
      url "${url(v, lx.name)}"
      sha256 "${lx.sha256}"
    end
  end

  def install
    bin.install Dir["*"].first => "fitllm"
  end

  test do
    assert_match "FITS", shell_output("#{bin}/fitllm 'Gemma 4 31b' --gpu 'RTX 5090'")
  end
end
`;
}

export function renderScoop(manifest) {
  const v = manifest.version;
  const win = pick(manifest, 'windows', 'x64', null);
  return `${JSON.stringify({
    version: v,
    description: 'Will this LLM fit on your GPU or Mac? Architecture-accurate memory estimates',
    homepage: 'https://fitllm.run',
    license: 'MIT',
    architecture: {
      '64bit': { url: url(v, win.name), hash: win.sha256, bin: [[win.name, 'fitllm']] },
    },
    checkver: { github: `https://github.com/${REPO}` },
    autoupdate: {
      architecture: {
        '64bit': { url: `https://github.com/${REPO}/releases/download/v$version/fitllm-v$version-windows-x64.exe` },
      },
    },
  }, null, 2)}\n`;
}

function parseArgs(argv) {
  const out = { manifest: join(ROOT, 'dist-bin', 'manifest.json'), outDir: join(ROOT, 'packaging') };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--manifest') { out.manifest = argv[i + 1]; i += 1; }
    else if (argv[i] === '--out') { out.outDir = argv[i + 1]; i += 1; }
    else throw new Error(`unknown argument: ${argv[i]}`);
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { manifest: manifestPath, outDir } = parseArgs(process.argv.slice(2));
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  for (const [os, arch, libc] of REQUIRED) pick(manifest, os, arch, libc); // fail fast
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'fitllm.rb'), renderFormula(manifest));
  writeFileSync(join(outDir, 'fitllm.json'), renderScoop(manifest));
  process.stdout.write(`${JSON.stringify({ version: manifest.version, wrote: ['fitllm.rb', 'fitllm.json'] })}\n`);
}
